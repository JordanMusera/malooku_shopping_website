const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = process.cwd();
const req = require('node:module').createRequire(root + '/package.json');
const ts = req('typescript'), mongoose = req('mongoose'), jwt = req('jsonwebtoken');
const { NextRequest } = req('next/server');
const db = 'malooku_tracking_test_' + Date.now();
process.env.MONGODB_URI = 'mongodb://127.0.0.1:27017/' + db;
process.env.JWT_SECRET = 'isolated-order-tracking-test-only';
const cache = new Map();
function load(file) {
  file = path.resolve(file); if (!path.extname(file)) file += '.ts';
  if (cache.has(file)) return cache.get(file).exports;
  const module = { exports: {} }; cache.set(file, module);
  const localRequire = name => name.startsWith('@/') ? load(root + '/src/' + name.slice(2)) : name.startsWith('.') ? load(path.resolve(path.dirname(file), name)) : req(name);
  const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText;
  vm.runInThisContext('(function(require,module,exports){' + code + '\n})', { filename: file })(localRequire, module, module.exports);
  return module.exports;
}
const request = (url, cookie = '', body) => new NextRequest('http://localhost:3000' + url, { method: body === undefined ? 'GET' : 'POST', headers: { cookie, 'Content-Type': 'application/json' }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
const json = async response => ({ status: response.status, cache: response.headers.get('Cache-Control'), body: await response.json() });
async function main() {
  await mongoose.connect(process.env.MONGODB_URI, { serverSelectionTimeoutMS: 5000 });
  const User = load(root + '/src/app/models/user').default;
  const Order = load(root + '/src/app/models/order').default;
  const Progress = load(root + '/src/app/models/orderprogress').default;
  const admin = await User.create({ username: 'Tracking admin', role: 'admin' });
  const customer = await User.create({ username: 'Tracking customer', role: 'user' });
  const other = await User.create({ username: 'Other customer', role: 'user' });
  const adminCookie = 'adminToken=' + jwt.sign({}, process.env.JWT_SECRET, { subject: String(admin._id), audience: 'malooku-admin', issuer: 'malooku' });
  const customerCookie = 'authToken=' + jwt.sign({ userId: String(customer._id) }, process.env.JWT_SECRET);
  const otherCookie = 'authToken=' + jwt.sign({ userId: String(other._id) }, process.env.JWT_SECRET);
  const controller = load(root + '/src/app/api/orders/controller/route');
  const tracking = load(root + '/src/app/api/orders/orderProgress/[id]/route');
  const base = { userId: String(customer._id), totalCost: 5000, shippingAddress: { street: 'Example Avenue', city: 'Nairobi', county: 'Nairobi' } };
  const order = await Order.create({ ...base, status: 'delivered' });
  await Progress.create({ orderId: String(order._id), totalCost: 1, orderProgress: [{ orderStatus: 'pending', date: '2026-10-01T10:00:00.000Z', description: 'Awaiting packaging and dispatch' }] });
  const get = async (id = order._id, cookie = customerCookie) => json(await tracking.GET(request('/api/orders/orderProgress/' + id, cookie), { params: { id: String(id) } }));
  const update = async (status, id = order._id, cookie = adminCookie) => json(await controller.POST(request('/api/orders/controller', cookie, { orderId: String(id), orderStatus: status })));
  let result = await get();
  assert.equal(result.status, 200); assert.equal(result.body.content.status, 'delivered');
  assert.equal(result.body.content.orderProgress.at(-1).orderStatus, 'delivered');
  assert.equal(result.body.content.orderProgress.at(-1).date, '', 'Do not invent dates for old admin changes');
  assert.equal(result.body.content.totalCost, 5000, 'Order details must also come from the order, not the stale history snapshot');
  assert.equal(result.body.content.shippingAddress.city, 'Nairobi');
  assert.match(result.cache, /no-store/);
  console.log('PASS: an existing delivered order with pending-only tracking displays delivered without changing live data or inventing a timestamp.');
  assert.equal((await get(order._id, '')).status, 401);
  assert.equal((await get(order._id, otherCookie)).status, 404);
  assert.equal((await get('invalid')).status, 400);
  assert.equal((await update('shipped', order._id, customerCookie)).status, 401);
  assert.equal((await update('invalid')).status, 400);
  assert.equal((await update('shipped', 'invalid')).status, 400);
  assert.equal((await update('shipped', new mongoose.Types.ObjectId())).status, 404);
  assert.equal((await Order.findById(order._id)).status, 'delivered');
  console.log('PASS: customer ownership, admin authentication, status validation and missing-order responses.');
  const fresh = await Order.create({ ...base, status: 'pending' });
  await Progress.create({ orderId: String(fresh._id), orderProgress: [{ orderStatus: 'pending', date: fresh.orderDate.toISOString(), description: 'Awaiting packaging and dispatch' }] });
  const save = await update('shipped', fresh._id);
  assert.equal(save.status, 200); assert.equal(save.body.content.status, 'shipped');
  let stored = await Order.findById(fresh._id);
  assert.equal(stored.statusHistory.length, 1); assert.equal(stored.statusHistory[0].orderStatus, 'shipped');
  assert.ok(Number.isFinite(Date.parse(stored.statusHistory[0].date)));
  result = await get(fresh._id);
  assert.deepEqual(result.body.content.orderProgress.map(event => event.orderStatus), ['pending', 'shipped']);
  assert.equal(result.body.content.status, save.body.content.status);
  const retries = await Promise.all(Array.from({ length: 5 }, () => update('shipped', fresh._id)));
  assert.ok(retries.every(r => r.status === 200));
  assert.equal((await Order.findById(fresh._id)).statusHistory.length, 1);
  await update('delivered', fresh._id);
  result = await get(fresh._id);
  assert.deepEqual(result.body.content.orderProgress.map(event => event.orderStatus), ['pending', 'shipped', 'delivered']);
  assert.equal(result.body.content.status, 'delivered');
  console.log('PASS: admin pending → shipped → delivered changes appear in customer tracking, with timestamps and no duplicate retry events.');
  const concurrent = await Order.create({ ...base, status: 'pending' });
  await Promise.all([update('shipped', concurrent._id), update('cancelled', concurrent._id)]);
  stored = await Order.findById(concurrent._id);
  assert.equal(stored.statusHistory.at(-1).orderStatus, stored.status);
  result = await get(concurrent._id);
  assert.equal(result.body.content.orderProgress.at(-1).orderStatus, stored.status);
  console.log('PASS: concurrent admin changes keep the final status and final history event consistent.');
  const originalUpdate = Order.findOneAndUpdate;
  Order.findOneAndUpdate = () => { throw Error('Simulated save failure'); };
  try { assert.equal((await update('cancelled', fresh._id)).status, 503); } finally { Order.findOneAndUpdate = originalUpdate; }
  stored = await Order.findById(fresh._id);
  assert.equal(stored.status, 'delivered'); assert.equal(stored.statusHistory.length, 2);
  const missingHistory = await Order.create({ ...base, status: 'shipped' });
  result = await get(missingHistory._id);
  assert.equal(result.body.content.status, 'shipped'); assert.equal(result.body.content.orderProgress.at(-1).orderStatus, 'shipped');
  const adminOrders = await json(await controller.GET(request('/api/orders/controller', adminCookie)));
  assert.equal(adminOrders.body.content.find(item => item._id === String(fresh._id)).status, (await get(fresh._id)).body.content.status);
  console.log('PASS: save failures preserve the prior status/history, and orders without a legacy tracking record remain trackable.');
}
main().catch(e => { console.error(e); process.exitCode = 1; }).finally(async () => {
  if (mongoose.connection.readyState === 1) { assert.equal(mongoose.connection.name, db); assert.ok(db.startsWith('malooku_tracking_test_')); await mongoose.connection.dropDatabase(); await mongoose.disconnect(); }
  console.log('Only a temporary local test database was used. No real orders or payments were modified.');
});
